void splash_show(void) {
    ESP_LOGI(TAG, "Showing splash screen...");
    
    display_fill_screen(COLOR_BLACK);
    
    int16_t x = (DISPLAY_WIDTH - LOGO_WIDTH) / 2;
    int16_t y = (DISPLAY_HEIGHT - LOGO_HEIGHT) / 2;
    
    // Fade-in effect
    for (int b = 0; b <= 255; b += 15) {
        uint16_t color = display_color565(b, b, b);
        display_draw_bitmap_vertical(x, y, debyte_logo, LOGO_WIDTH, LOGO_HEIGHT, color);
        vTaskDelay(pdMS_TO_TICKS(30));
    }
    
    // Hold logo
    vTaskDelay(pdMS_TO_TICKS(1000));
    
    // Fade-out effect
    for (int b = 255; b >= 0; b -= 15) {
        uint16_t color = display_color565(b, b, b);
        display_draw_bitmap_vertical(x, y, debyte_logo, LOGO_WIDTH, LOGO_HEIGHT, color);
        vTaskDelay(pdMS_TO_TICKS(30));
    }
    
    display_fill_screen(COLOR_BLACK);
    
    ESP_LOGI(TAG, "Splash complete");
}
